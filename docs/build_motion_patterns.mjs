#!/usr/bin/env node
// docs/build_motion_patterns.mjs: writes docs/motion-patterns.md from the pattern pages in
// skills/brief2motion/references/patterns/, so the human-facing list cannot drift from the recipes the agent reads.
//   node docs/build_motion_patterns.mjs            write the file
//   node docs/build_motion_patterns.mjs --check    exit 1 if the file is out of date (tests/docs.test.mjs runs this)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'skills/brief2motion/references/patterns');
const OUT = path.join(ROOT, 'docs/motion-patterns.md');
const REL = '../skills/brief2motion/references/patterns';

const field = (md, name) => (md.match(new RegExp(`^\\*\\*${name}:\\*\\* (.+)$`, 'm')) || [])[1]?.trim() || '';
const section = (md, name) => {
  const m = md.match(new RegExp(`^## ${name}[^\\n]*\\n+([\\s\\S]*?)(?=\\n## |(?![\\s\\S]))`, 'm'));
  return m ? m[1].trim().split(/\n\s*\n/)[0].replace(/\s*\n\s*/g, ' ') : '';
};

// GitHub's heading anchor: lower case, punctuation dropped, spaces to hyphens.
export const slug = (t) => t.toLowerCase().replace(/[^\p{L}\p{N} _-]/gu, '').replace(/ /g, '-');

export function readPatterns() {
  const index = fs.readFileSync(path.join(DIR, 'README.md'), 'utf8');
  const rows = [...index.matchAll(/^\| \[([a-z0-9-]+)\]\(\1\.md\) \| ([^|]+) \| ([^|]+) \| ([^|]+) \|$/gm)];
  return rows.map(([, id, says, stack, checks]) => {
    const md = fs.readFileSync(path.join(DIR, `${id}.md`), 'utf8');
    const title = (md.match(/^# (.+)$/m) || [])[1].trim();
    const what = md.split('\n').slice(1).join('\n').trim().split(/\n\s*\n/)[0].replace(/\s*\n\s*/g, ' ');
    return {
      id, title, what, says: says.trim(), stackShort: stack.trim(), checks: checks.trim(),
      use: field(md, 'Use when'), not: field(md, 'Not when'), reduced: section(md, 'Reduced motion'),
    };
  });
}

export function render(patterns) {
  const out = [];
  out.push('# Motion patterns');
  out.push('');
  out.push(`<!-- Generated by docs/build_motion_patterns.mjs from ${REL.slice(3)}/. Edit the pattern pages, then run the script. -->`);
  out.push('');
  out.push(`brief2motion carries ${patterns.length} motion pattern recipes: the scroll animations, hover effects, page transitions and 3D moments that briefs ask for most. Each recipe says when to use the pattern and when not, which stack builds it, a performance and accessibility budget, what the page does for a visitor who has reduced motion switched on, and how the checks verify it. The router (\`scripts/route.mjs\`) lists the patterns whose words appear in a brief, and the agent starts from the recipe's sketch.`);
  out.push('');
  out.push('The sketches are starting points, not tested pages: their JavaScript parses and the kit files they import exist (`tests/patterns.test.mjs`). The tested pages are the [examples](../examples/). Every pattern follows the same frame: content is in the HTML and readable without JavaScript, motion is created only when the visitor has not asked for reduced motion, and the page reports its motion state so the checker can test both branches. The timing and easing rules all of them share are in [motion-doctrine.md](../skills/brief2motion/references/motion-doctrine.md).');
  out.push('');
  out.push('## All patterns at a glance');
  out.push('');
  out.push('| Pattern | The brief says | Stack | Checks that cover it |');
  out.push('|---|---|---|---|');
  for (const p of patterns) out.push(`| [${p.title}](#${slug(p.title)}) | ${p.says} | ${p.stackShort} | ${p.checks} |`);
  out.push('');
  out.push('## The patterns');
  for (const p of patterns) {
    out.push('');
    out.push(`### ${p.title}`);
    out.push('');
    out.push(p.what);
    out.push('');
    out.push(`- **Use when:** ${p.use}`);
    out.push(`- **Not when:** ${p.not}`);
    out.push(`- **Reduced motion:** ${p.reduced}`);
    out.push(`- **Recipe:** [${p.id}.md](${REL}/${p.id}.md)`);
  }
  out.push('');
  out.push('## Adding a pattern');
  out.push('');
  out.push(`Write the page in [${REL.slice(3)}/](${REL}/) with the same sections as the others, add it to the index in its README and to \`patterns\` in \`references/routing.json\`, then run \`node docs/build_motion_patterns.mjs\` and \`node --test tests/*.test.mjs\`.`);
  out.push('');
  return out.join('\n');
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const text = render(readPatterns());
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (now !== text) { console.error('docs/motion-patterns.md is out of date: run node docs/build_motion_patterns.mjs'); process.exit(1); }
    console.log('docs/motion-patterns.md is current');
  } else {
    fs.writeFileSync(OUT, text);
    console.log(`wrote docs/motion-patterns.md (${readPatterns().length} patterns)`);
  }
}
